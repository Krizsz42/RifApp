create or replace function private.sesion_valida(p_token text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
    v_hash text;
begin
    if p_token is null or length(p_token) < 32 then
        return false;
    end if;

    v_hash := encode(extensions.digest(p_token, 'sha256'), 'hex');

    return exists (
        select 1
        from private.admin_sessions s
        where s.token_hash = v_hash
          and s.expira > now()
    );
end;
$$;

create or replace function private.exigir_sesion(p_token text)
returns void
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
    if not private.sesion_valida(p_token) then
        raise exception 'Sesión no válida o expirada. Vuelve a entrar con el PIN.'
            using errcode = '28000';
    end if;
end;
$$;

create or replace function private.bump_version()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.config
       set valor = ((valor::integer) + 1)::text
     where clave = 'version';

    if not found then
        insert into public.config (clave, valor) values ('version', '1');
    end if;
end;
$$;

create or replace function private.nueva_sesion(p_dias integer default 30)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    v_token text;
    v_expira timestamptz;
begin
    delete from private.admin_sessions where expira < now() - interval '1 day';

    v_token := encode(extensions.gen_random_bytes(32), 'hex');
    v_expira := now() + make_interval(days => greatest(p_dias, 1));

    insert into private.admin_sessions (token_hash, expira)
    values (encode(extensions.digest(v_token, 'sha256'), 'hex'), v_expira);

    return jsonb_build_object(
        'token', v_token,
        'expira', v_expira
    );
end;
$$;

revoke all on function private.sesion_valida(text) from public, anon, authenticated;
revoke all on function private.exigir_sesion(text) from public, anon, authenticated;
revoke all on function private.bump_version() from public, anon, authenticated;
revoke all on function private.nueva_sesion(integer) from public, anon, authenticated;

