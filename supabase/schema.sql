-- ---------------------------------------------------------------------
-- Tablas públicas (solo lectura para los visitantes, escritura vía RPC)
-- ---------------------------------------------------------------------

create table if not exists public.config (
    clave text primary key,
    valor text not null
);

create table if not exists public.numeros (
    numero integer primary key check (numero > 0),
    nombre text not null default '',
    telefono text not null default '',
    nota text not null default '',
    abonado numeric(12, 2) not null default 0 check (abonado >= 0),
    estado text not null default 'disponible'
        check (estado in ('disponible', 'apartado', 'pagado')),
    actualizado timestamptz not null default now()
);

create table if not exists public.abonos (
    id bigint generated by default as identity primary key,
    numero integer not null references public.numeros(numero) on delete cascade,
    titular text not null default '',
    monto numeric(12, 2) not null check (monto > 0),
    nota text not null default '',
    fecha timestamptz not null default now()
);

create index if not exists idx_abonos_numero on public.abonos(numero);

create table if not exists public.sorteos (
    id bigint generated by default as identity primary key,
    numero integer not null,
    nombre text not null default '',
    telefono text not null default '',
    premio text not null default '',
    fecha timestamptz not null default now()
);

insert into public.config (clave, valor) values
