    ('premio', ''),
    ('total_numeros', '200'),
    ('precio', '2000'),
    ('moneda', '$'),
    ('version', '0')
on conflict (clave) do nothing;

insert into public.numeros (numero)
select generate_series(
    1,
    coalesce((select valor::integer from public.config where clave = 'total_numeros'), 200)
)
on conflict (numero) do nothing;

