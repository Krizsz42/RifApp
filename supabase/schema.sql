create or replace function public.estado_rifa()
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_precio numeric := 0;
    v_total integer := 0;
    v_version integer := 0;
    v_nombre text := 'Mi rifa';
    v_premio text := '';
    v_moneda text := '';
    v_numeros jsonb;
    v_sorteos jsonb;
    v_apartados integer := 0;
    v_pagados integer := 0;
    v_disponibles integer := 0;
    v_recaudado numeric := 0;
    v_por_cobrar numeric := 0;
begin
    select coalesce((select valor from public.config where clave = 'precio')::numeric, 0)
      into v_precio;
    select coalesce((select valor from public.config where clave = 'total_numeros')::integer, 0)
      into v_total;
    select coalesce((select valor from public.config where clave = 'version')::integer, 0)
      into v_version;
    select coalesce((select valor from public.config where clave = 'rifa_nombre'), 'Mi rifa')
      into v_nombre;
    select coalesce((select valor from public.config where clave = 'premio'), '')
      into v_premio;
    select coalesce((select valor from public.config where clave = 'moneda'), '')
      into v_moneda;

    select
        coalesce(count(*) filter (where estado = 'apartado'), 0)::integer,
        coalesce(count(*) filter (where estado = 'pagado'), 0)::integer,
        coalesce(count(*) filter (where estado = 'disponible'), 0)::integer,
        coalesce(sum(abonado) filter (where estado <> 'disponible'), 0),
        coalesce(sum(greatest(v_precio - abonado, 0)) filter (where estado <> 'disponible'), 0)
      into v_apartados, v_pagados, v_disponibles, v_recaudado, v_por_cobrar
      from public.numeros;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'numero', numero,
                'nombre', nombre,
                'telefono', telefono,
                'nota', nota,
                'abonado', round(abonado, 2),
                'saldo', round(greatest(v_precio - abonado, 0), 2),
                'estado', estado,
                'actualizado', to_char(actualizado at time zone 'America/Santiago',
                                        'YYYY-MM-DD HH24:MI:SS')
            )
            order by numero
        ),
        '[]'::jsonb
    )
      into v_numeros
      from public.numeros;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', id,
                'numero', numero,
                'nombre', nombre,
                'telefono', telefono,
                'premio', premio,
                'fecha', to_char(fecha at time zone 'America/Santiago',
                                 'YYYY-MM-DD HH24:MI:SS')
            )
            order by id desc
        ),
        '[]'::jsonb
    )
      into v_sorteos
      from (
          select id, numero, nombre, telefono, premio, fecha
          from public.sorteos
          order by id desc
      ) s;

    return jsonb_build_object(
        'version', v_version,
        'config', jsonb_build_object(
            'rifa_nombre', v_nombre,
            'premio', v_premio,
            'total_numeros', v_total,
            'precio', v_precio,
            'moneda', v_moneda
        ),
        'stats', jsonb_build_object(
            'total', v_disponibles + v_apartados + v_pagados,
            'disponibles', v_disponibles,
            'apartados', v_apartados,
            'pagados', v_pagados,
            'vendidos', v_apartados + v_pagados,
            'recaudado', round(v_recaudado, 2),
            'por_cobrar', round(v_por_cobrar, 2)
        ),
        'numeros', v_numeros,
        'sorteos', v_sorteos
    );
end;
$$;

create or replace function public.detalle_numero(p_numero integer)
returns jsonb
language plpgsql
stable
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_precio numeric := 0;
    v_fila public.numeros%rowtype;
    v_abonos jsonb;
begin
    select coalesce((select valor from public.config where clave = 'precio')::numeric, 0)
      into v_precio;

    select * into v_fila
      from public.numeros
     where numero = p_numero;

    if not found then
        raise exception 'Ese número no existe' using errcode = 'P0002';
    end if;

    select coalesce(
        jsonb_agg(
            jsonb_build_object(
                'id', id,
                'monto', round(monto, 2),
                'nota', nota,
                'fecha', to_char(fecha at time zone 'America/Santiago',
                                 'YYYY-MM-DD HH24:MI:SS'),
                'titular', titular
            )
            order by id desc
        ),
        '[]'::jsonb
    )
      into v_abonos
      from public.abonos
     where numero = p_numero;

    return jsonb_build_object(
        'numero', jsonb_build_object(
            'numero', v_fila.numero,
            'nombre', v_fila.nombre,
            'telefono', v_fila.telefono,
            'nota', v_fila.nota,
            'abonado', round(v_fila.abonado, 2),
            'saldo', round(greatest(v_precio - v_fila.abonado, 0), 2),
            'estado', v_fila.estado,
            'actualizado', to_char(v_fila.actualizado at time zone 'America/Santiago',
                                   'YYYY-MM-DD HH24:MI:SS')
        ),
        'abonos', v_abonos
    );
end;
$$;

