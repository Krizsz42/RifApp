create or replace function public.cerrar_sesion(p_token text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
    if p_token is null or length(p_token) < 32 then
        return false;
    end if;

    delete from private.admin_sessions
     where token_hash = encode(extensions.digest(p_token, 'sha256'), 'hex');

    return true;
end;
$$;

create or replace function public.verificar_pin(
    p_pin text,
    p_dispositivo text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_hash text;
    v_ip text := '';
    v_disp text;
    v_fallos integer := 0;
    v_sesion jsonb;
begin
    if p_pin is null or length(p_pin) < 1 or length(p_pin) > 200 then
        raise exception 'PIN no válido' using errcode = '28P01';
    end if;

    v_disp := left(coalesce(nullif(trim(p_dispositivo), ''), 'anonimo'), 100);

    begin
        v_ip := coalesce(
            trim(split_part(
                (current_setting('request.headers', true)::jsonb ->> 'x-forwarded-for'),
                ',',
                1
            )),
            ''
        );
    exception when others then
        v_ip := '';
    end;

    delete from private.pin_intentos
     where creado < now() - interval '1 day';

    select count(*)::integer
      into v_fallos
      from private.pin_intentos
     where exito = false
       and creado > now() - interval '15 minutes'
       and (
           (v_ip <> '' and ip = v_ip)
           or dispositivo = v_disp
       );

    if v_fallos >= 8 then
        -- Se devuelve un JSON en vez de lanzar una excepción para que el
        -- registro del intento no se revierta con la transacción.
        return jsonb_build_object(
            'ok', false,
            'error', 'Demasiados intentos fallidos. Espera 15 minutos y vuelve a probar.',
            'code', '28P01'
        );
    end if;

    select pin_hash into v_hash
      from private.admin_pin
     where id = 1;

    if v_hash is null then
        raise exception 'El PIN de administrador todavía no está configurado. Revisa la guía de despliegue.'
            using errcode = 'P0001';
    end if;

    if extensions.crypt(p_pin, v_hash) = v_hash then
        insert into private.pin_intentos (dispositivo, ip, exito)
        values (v_disp, v_ip, true);

        delete from private.pin_intentos
         where exito = false
           and (
               (v_ip <> '' and ip = v_ip)
               or dispositivo = v_disp
           );

        v_sesion := private.nueva_sesion(30);

        return jsonb_build_object('ok', true) || v_sesion;
    end if;

    insert into private.pin_intentos (dispositivo, ip, exito)
    values (v_disp, v_ip, false);

    return jsonb_build_object('ok', false, 'error', 'PIN incorrecto', 'code', '28P01');
end;
$$;

create or replace function public.cambiar_pin(
    p_token text,
    p_pin_actual text,
    p_pin_nuevo text
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_hash text;
    v_sesion jsonb;
begin
    perform private.exigir_sesion(p_token);

    if p_pin_nuevo is null or length(p_pin_nuevo) < 6 or length(p_pin_nuevo) > 200 then
        raise exception 'El PIN nuevo debe tener al menos 6 caracteres'
            using errcode = 'P0001';
    end if;

    select pin_hash into v_hash
      from private.admin_pin
     where id = 1;

    if v_hash is null or extensions.crypt(coalesce(p_pin_actual, ''), v_hash) <> v_hash then
        raise exception 'El PIN actual no es correcto' using errcode = '28P01';
    end if;

    insert into private.admin_pin (id, pin_hash, actualizado)
    values (1, extensions.crypt(p_pin_nuevo, extensions.gen_salt('bf', 12)), now())
    on conflict (id) do update
        set pin_hash = excluded.pin_hash,
            actualizado = excluded.actualizado;

    -- Al cambiar el PIN se cierran todas las sesiones y se entrega una nueva
    -- al dispositivo que hizo el cambio.
    delete from private.admin_sessions;

    v_sesion := private.nueva_sesion(30);

    return jsonb_build_object('ok', true) || v_sesion;
end;
$$;

