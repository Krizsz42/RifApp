create or replace function public.asignar_numeros(
    p_token text,
    p_numeros integer[],
    p_nombre text,
    p_telefono text default '',
    p_nota text default '',
    p_abono numeric default 0
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_nums integer[];
    v_total integer := 0;
    v_precio numeric := 0;
    v_nombre text;
    v_telefono text;
    v_nota text;
    v_abono numeric;
    v_n integer;
    v_dueno text;
    v_estado_actual text;
    v_nuevo_estado text;
    v_marca timestamptz := now();
begin
    perform private.exigir_sesion(p_token);

    -- Serializa las escrituras para que un cambio de precio no se cruce
    -- con una asignación o un abono.
    perform 1 from public.config where clave = 'version' for update;

    if p_numeros is null or array_length(p_numeros, 1) is null then
        raise exception 'Selecciona al menos un número' using errcode = 'P0001';
    end if;

    v_nums := array(
        select distinct n
        from unnest(p_numeros) as t(n)
        order by n
    );

    v_nombre := left(trim(coalesce(p_nombre, '')), 80);
    v_telefono := left(trim(coalesce(p_telefono, '')), 40);
    v_nota := left(trim(coalesce(p_nota, '')), 300);
    v_abono := round(coalesce(p_abono, 0), 2);

    if v_nombre = '' then
        raise exception 'Escribe el nombre del comprador' using errcode = 'P0001';
    end if;

    if v_abono < 0 then
        raise exception 'El abono no puede ser negativo' using errcode = 'P0001';
    end if;

    select coalesce((select valor from public.config where clave = 'precio')::numeric, 0)
      into v_precio;
    select coalesce((select valor from public.config where clave = 'total_numeros')::integer, 0)
      into v_total;

    if v_abono > v_precio + 0.001 then
        raise exception 'El abono no puede ser mayor que el precio del número'
            using errcode = 'P0001';
    end if;

    foreach v_n in array v_nums loop
        if v_n is null then
            raise exception 'La lista de números no es válida' using errcode = 'P0001';
        end if;

        if v_n < 1 or v_n > v_total then
            raise exception 'El número % está fuera del rango de la rifa', v_n
                using errcode = 'P0001';
        end if;

        select estado, nombre
          into v_estado_actual, v_dueno
          from public.numeros
         where numero = v_n
           for update;

        if not found then
            raise exception 'El número % no existe', v_n using errcode = 'P0002';
        end if;

        if v_estado_actual <> 'disponible' then
            raise exception 'El número % ya está ocupado por %',
                v_n, coalesce(nullif(v_dueno, ''), 'otra persona')
                using errcode = 'P0001';
        end if;
    end loop;

    v_nuevo_estado := case
        when v_abono >= v_precio - 0.001 then 'pagado'
        else 'apartado'
    end;

    foreach v_n in array v_nums loop
        update public.numeros
           set nombre = v_nombre,
               telefono = v_telefono,
               nota = v_nota,
               abonado = v_abono,
               estado = v_nuevo_estado,
               actualizado = v_marca
         where numero = v_n;

        if v_abono > 0 then
            insert into public.abonos (numero, titular, monto, nota, fecha)
            values (v_n, v_nombre, v_abono, 'Abono inicial', v_marca);
        end if;
    end loop;

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.registrar_abono(
    p_token text,
    p_numero integer,
    p_monto numeric,
    p_nota text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_precio numeric := 0;
    v_fila public.numeros%rowtype;
    v_monto numeric;
    v_saldo numeric;
    v_nuevo numeric;
    v_nuevo_estado text;
    v_marca timestamptz := now();
begin
    perform private.exigir_sesion(p_token);

    perform 1 from public.config where clave = 'version' for update;

    v_monto := round(coalesce(p_monto, 0), 2);

    if v_monto <= 0 then
        raise exception 'El abono debe ser mayor que cero' using errcode = 'P0001';
    end if;

    select * into v_fila
      from public.numeros
     where numero = p_numero
       for update;

    if not found then
        raise exception 'Ese número no existe' using errcode = 'P0002';
    end if;

    if v_fila.estado = 'disponible' then
        raise exception 'Ese número está disponible, primero asígnalo'
            using errcode = 'P0001';
    end if;

    select coalesce((select valor from public.config where clave = 'precio')::numeric, 0)
      into v_precio;

    v_saldo := greatest(v_precio - v_fila.abonado, 0);

    if v_saldo <= 0.001 then
        raise exception 'Ese número ya está pagado por completo' using errcode = 'P0001';
    end if;

    if v_monto > v_saldo + 0.001 then
        raise exception 'El abono supera el saldo pendiente (%)', round(v_saldo, 2)
            using errcode = 'P0001';
    end if;

    v_nuevo := round(v_fila.abonado + v_monto, 2);
    v_nuevo_estado := case
        when v_nuevo >= v_precio - 0.001 then 'pagado'
        else 'apartado'
    end;

    update public.numeros
       set abonado = v_nuevo,
           estado = v_nuevo_estado,
           actualizado = v_marca
     where numero = p_numero;

    insert into public.abonos (numero, titular, monto, nota, fecha)
    values (p_numero, v_fila.nombre, v_monto, left(trim(coalesce(p_nota, '')), 200), v_marca);

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.editar_numero(
    p_token text,
    p_numero integer,
    p_nombre text,
    p_telefono text default '',
    p_nota text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_nombre text;
    v_estado_actual text;
begin
    perform private.exigir_sesion(p_token);

    perform 1 from public.config where clave = 'version' for update;

    v_nombre := left(trim(coalesce(p_nombre, '')), 80);

    if v_nombre = '' then
        raise exception 'El nombre no puede quedar vacío' using errcode = 'P0001';
    end if;

    select estado into v_estado_actual
      from public.numeros
     where numero = p_numero
       for update;

    if not found then
        raise exception 'Ese número no existe' using errcode = 'P0002';
    end if;

    if v_estado_actual = 'disponible' then
        raise exception 'Ese número está disponible' using errcode = 'P0001';
    end if;

    update public.numeros
       set nombre = v_nombre,
           telefono = left(trim(coalesce(p_telefono, '')), 40),
           nota = left(trim(coalesce(p_nota, '')), 300),
           actualizado = now()
     where numero = p_numero;

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.liberar_numeros(
    p_token text,
    p_numeros integer[]
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_nums integer[];
    v_n integer;
begin
    perform private.exigir_sesion(p_token);

    perform 1 from public.config where clave = 'version' for update;

    if p_numeros is null or array_length(p_numeros, 1) is null then
        raise exception 'Selecciona al menos un número' using errcode = 'P0001';
    end if;

    v_nums := array(
        select distinct n
        from unnest(p_numeros) as t(n)
        order by n
    );

    foreach v_n in array v_nums loop
        if v_n is null then
            raise exception 'La lista de números no es válida' using errcode = 'P0001';
        end if;

        if not exists (select 1 from public.numeros where numero = v_n) then
            raise exception 'El número % no existe', v_n using errcode = 'P0002';
        end if;

        update public.numeros
           set nombre = '',
               telefono = '',
               nota = '',
               abonado = 0,
               estado = 'disponible',
               actualizado = now()
         where numero = v_n;

        delete from public.abonos where numero = v_n;
    end loop;

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.guardar_config(
    p_token text,
    p_rifa_nombre text,
    p_premio text,
    p_total_numeros integer,
    p_precio numeric,
    p_moneda text
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_nombre text;
    v_premio text;
    v_moneda text;
    v_total integer;
    v_precio numeric;
    v_max_ocupado integer := 0;
begin
    perform private.exigir_sesion(p_token);

    v_nombre := left(trim(coalesce(p_rifa_nombre, '')), 80);
    v_premio := left(trim(coalesce(p_premio, '')), 200);
    v_moneda := left(trim(coalesce(p_moneda, '')), 8);
    v_total := coalesce(p_total_numeros, 0);
    v_precio := round(coalesce(p_precio, 0), 2);

    if v_nombre = '' then
        v_nombre := 'Mi rifa';
    end if;

    if v_total < 1 or v_total > 10000 then
        raise exception 'La cantidad de números debe estar entre 1 y 10000'
            using errcode = 'P0001';
    end if;

    if v_precio < 0 then
        raise exception 'El precio no puede ser negativo' using errcode = 'P0001';
    end if;

    -- Serializa los cambios de configuración.
    perform 1 from public.config where clave = 'version' for update;

    select coalesce(max(numero), 0)
      into v_max_ocupado
      from public.numeros
     where estado <> 'disponible';

    if v_max_ocupado > v_total then
        raise exception 'No puedes reducir a % números: el número % ya está vendido',
            v_total, v_max_ocupado
            using errcode = 'P0001';
    end if;

    insert into public.numeros (numero)
    select generate_series(1, v_total)
    on conflict (numero) do nothing;

    delete from public.numeros
     where numero > v_total
       and estado = 'disponible';

    insert into public.config (clave, valor) values
        ('rifa_nombre', v_nombre),
        ('premio', v_premio),
        ('moneda', v_moneda),
        ('total_numeros', v_total::text),
        ('precio', v_precio::text)
    on conflict (clave) do update
        set valor = excluded.valor;

    update public.numeros
       set estado = case
           when abonado >= v_precio - 0.001 then 'pagado'
           else 'apartado'
       end
     where estado <> 'disponible';

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.realizar_sorteo(
    p_token text,
    p_solo_pagados boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_numero integer;
    v_nombre text;
    v_telefono text;
    v_premio text;
    v_marca timestamptz := now();
    v_id bigint;
begin
    perform private.exigir_sesion(p_token);

    perform 1 from public.config where clave = 'version' for update;

    if coalesce(p_solo_pagados, false) then
        select numero, nombre, telefono
          into v_numero, v_nombre, v_telefono
          from public.numeros
         where estado = 'pagado'
         order by random()
         limit 1;
    else
        select numero, nombre, telefono
          into v_numero, v_nombre, v_telefono
          from public.numeros
         where estado <> 'disponible'
         order by random()
         limit 1;
    end if;

    if not found then
        raise exception '%',
            case when coalesce(p_solo_pagados, false)
                 then 'No hay números pagados para sortear'
                 else 'Todavía no hay números vendidos para sortear'
            end
            using errcode = 'P0001';
    end if;

    select coalesce((select valor from public.config where clave = 'premio'), '')
      into v_premio;

    insert into public.sorteos (numero, nombre, telefono, premio, fecha)
    values (v_numero, v_nombre, v_telefono, v_premio, v_marca)
    returning id into v_id;

    perform private.bump_version();

    return jsonb_build_object(
        'ok', true,
        'ganador', jsonb_build_object(
            'id', v_id,
            'numero', v_numero,
            'nombre', v_nombre,
            'telefono', v_telefono,
            'premio', v_premio,
            'fecha', to_char(v_marca at time zone 'America/Santiago',
                             'YYYY-MM-DD HH24:MI:SS')
        ),
        'estado', public.estado_rifa()
    );
end;
$$;

create or replace function public.eliminar_sorteo(
    p_token text,
    p_id bigint
)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
begin
    perform private.exigir_sesion(p_token);

    perform 1 from public.config where clave = 'version' for update;

    delete from public.sorteos where id = p_id;

    if not found then
        raise exception 'Ese sorteo ya no existe' using errcode = 'P0002';
    end if;

    perform private.bump_version();

    return jsonb_build_object('ok', true, 'estado', public.estado_rifa());
end;
$$;

create or replace function public.respaldo_rifa(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = 'public, pg_temp'
as $$
declare
    v_abonos jsonb;
begin
    perform private.exigir_sesion(p_token);

    select coalesce(jsonb_agg(to_jsonb(a) order by a.id), '[]'::jsonb)
      into v_abonos
      from public.abonos a;

    return jsonb_build_object(
        'generado', to_char(now() at time zone 'America/Santiago',
                            'YYYY-MM-DD HH24:MI:SS'),
        'estado', public.estado_rifa(),
        'abonos', v_abonos
    );
end;
$$;

